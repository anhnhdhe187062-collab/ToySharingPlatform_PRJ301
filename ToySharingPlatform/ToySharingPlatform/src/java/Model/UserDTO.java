package Model;

/**
 *
 * @author ADMIN
 */
public class UserDTO {
    String userID;
    String fullName;
    String email;
    int roleID;

    public UserDTO() {
    }

    public UserDTO(String userID, String fullName, String email, int roleID) {
        this.userID = userID;
        this.fullName = fullName;
        this.email = email;
        this.roleID = roleID;
    }

    public String getUserID() {
        return userID;
    }

    public void setUserID(String userID) {
        this.userID = userID;
    }

    public String getFullName() {
        return fullName;
    }

    public void setFullName(String fullName) {
        this.fullName = fullName;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public int getRoleID() {
        return roleID;
    }

    public void setRoleID(int roleID) {
        this.roleID = roleID;
    }
    
}
